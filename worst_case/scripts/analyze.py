"""Anatomy of the optimal sequences: per-pass comparisons on the certified worst-case input, and the
numerical-semigroup view (which distances can still be out of order before each pass).

Writes results/anatomy.md / results/anatomy.json
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results")


def per_pass(perm, gaps):
    a = list(perm)
    n = len(a)
    out = []
    for h in sorted([g for g in gaps if g < n], reverse=True):
        c = 0
        for i in range(h, n):
            v, j = a[i], i
            while j >= h:
                c += 1
                if a[j - h] > v:
                    a[j] = a[j - h]; j -= h
                else:
                    break
            a[j] = v
        out.append((h, c))
    assert a == sorted(a)
    return out


def unsorted_distances(gens, n):
    """distances 1..n-1 NOT in the numerical semigroup generated by gens"""
    S = [False] * (2 * n + 1)
    S[0] = True
    for d in range(1, 2 * n + 1):
        S[d] = any(d >= g and S[d - g] for g in gens)
    return [d for d in range(1, n) if not S[d]]


def main():
    summ = json.load(open(os.path.join(RES, "summary.json")))
    rows, data = [], {}
    for key in sorted(summ, key=int):
        s = summ[key]
        if not s["optimal"]:
            continue
        n = s["N"]
        best = s["optimal"][0]
        seq = best["seq"]
        pp = per_pass(best["worst_input"], seq)
        tot = sum(c for _, c in pp)
        gaps_desc = sorted([g for g in seq if g < n], reverse=True)
        final_unsorted = unsorted_distances([g for g in gaps_desc if g > 1], n)
        data[n] = {"seq": seq, "W": s["W"], "per_pass": pp, "total": tot,
                   "final_pass_unsorted_distances": final_unsorted}
        rows.append(f"| {n} | {{{','.join(map(str, seq))}}} | {s['W']} | "
                    + " + ".join(f"{c}@{h}" for h, c in pp)
                    + f" | {len(final_unsorted)}: {{{','.join(map(str, final_unsorted[:12]))}{',…' if len(final_unsorted) > 12 else ''}}} |")
        if tot != s["W"]:
            rows[-1] += f" (stored input reaches {tot}; certified value {s['W']} from DP without reconstruction)"
            data[n]["witness_short"] = True
    md = ["| N | optimal sequence | W | comparisons per pass on the worst input (count@gap) | distances still unsorted before the final pass |",
          "|---|---|---|---|---|"] + rows
    open(os.path.join(RES, "anatomy.md"), "w").write("\n".join(md) + "\n")
    json.dump(data, open(os.path.join(RES, "anatomy.json"), "w"), indent=1)
    print("\n".join(md))


if __name__ == "__main__":
    main()
